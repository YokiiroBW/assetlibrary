def generated_outputs() -> dict[Path, bytes]:
    messages = load_messages()
    digest = contract_digest(CONTRACT_ROOT)
    shape = shape_document(messages, digest)
    stamp = f"{digest}\n".encode("ascii")
    outputs: dict[Path, bytes] = {
        SDK_ROOT / "dotnet" / ".contract-source.sha256": stamp,
        SDK_ROOT / "dotnet" / "AssetLink.Generated.cs": render_csharp(messages, digest).encode("utf-8"),
        SDK_ROOT / "typescript" / ".contract-source.sha256": stamp,
        SDK_ROOT / "typescript" / "src" / "generated.ts": render_typescript(messages, digest).encode("utf-8"),
        SDK_ROOT / "kotlin" / ".contract-source.sha256": stamp,
        SDK_ROOT / "kotlin" / "src" / "main" / "kotlin" / "app" / "assetlibrary" / "assetlink" / "AssetLink.Generated.kt": render_kotlin(messages, digest).encode("utf-8"),
    }
    hashes = {
        path.relative_to(SDK_ROOT).as_posix(): hashlib.sha256(content).hexdigest()
        for path, content in sorted(outputs.items(), key=lambda item: item[0].as_posix())
    }
    manifest = {
        "generator": "scripts/generate_assetlink_sdks.py",
        "generator_version": GENERATOR_VERSION,
        "contract_root": "contracts/assetlink",
        "contract_sha256": digest,
        "schema_count": len(messages) + 1,
        "message_count": len(messages),
        "messages": shape["messages"],
        "generated_files": hashes,
    }
    outputs[SDK_ROOT / "generation-manifest.json"] = json_bytes(manifest)
    return outputs


def unexpected_generated_files(expected: set[Path]) -> list[Path]:
    unexpected: list[Path] = []
    for target in (SDK_ROOT / "dotnet", SDK_ROOT / "typescript", SDK_ROOT / "kotlin"):
        if not target.exists():
            continue
        for path in target.rglob("*"):
            if not path.is_file() or path in expected:
                continue
            if any(part.lower() in IGNORED_GENERATED_DIRECTORIES for part in path.relative_to(target).parts):
                continue
            try:
                prefix = path.read_text(encoding="utf-8")[:512].lower()
            except (OSError, UnicodeError):
                continue
            if any(marker in prefix for marker in GENERATED_MARKERS):
                unexpected.append(path)
    return sorted(unexpected)


def display_path(path: Path) -> str:
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def check(outputs: dict[Path, bytes]) -> int:
    errors: list[str] = []
    for path, expected in outputs.items():
        if not path.is_file():
            errors.append(f"missing generated file: {display_path(path)}")
        elif path.read_bytes() != expected:
            errors.append(f"stale or hand-edited generated file: {display_path(path)}")
    for path in unexpected_generated_files(set(outputs)):
        errors.append(f"unexpected generated file: {display_path(path)}")
    if errors:
        for error in errors:
            print(f"ERROR: {error}", file=sys.stderr)
        return 1
    print(f"AssetLink SDK generation is current ({len(outputs)} generated files).")
    return 0


def write(outputs: dict[Path, bytes]) -> None:
    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(content)
    try:
        contract_label = CONTRACT_ROOT.relative_to(ROOT).as_posix()
    except ValueError:
        contract_label = str(CONTRACT_ROOT)
    print(f"Generated {len(outputs)} AssetLink SDK files from {contract_label}.")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Fail if generated output differs without writing files.")
    args = parser.parse_args()
    try:
        outputs = generated_outputs()
    except (OSError, UnicodeError, ValueError, json.JSONDecodeError) as exc:
        print(f"ERROR: cannot generate AssetLink SDKs: {exc}", file=sys.stderr)
        return 2
    if args.check:
        return check(outputs)
    write(outputs)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
