def typescript_type(specification: dict[str, Any]) -> str:
    kind = field_kind(specification)
    return {
        "string": "string",
        "integer": "number",
        "boolean": "boolean",
        "object": "Record<string, unknown>",
        "string_array": "readonly string[]",
        "object_array": "readonly Record<string, unknown>[]",
    }[kind]


def render_typescript(messages: list[MessageSchema], digest: str) -> str:
    interfaces: list[str] = []
    for message in messages:
        fields = []
        required = set(message.document.get("required", []))
        for name, specification in message.document["properties"].items():
            marker = "" if name in required else "?"
            field_type = f'"{message.message_type}"' if name == "message_type" else typescript_type(specification)
            fields.append(f"  {name}{marker}: {field_type};")
        interfaces.append(
            f"export interface {message.class_name.removesuffix('Message')} {{\n"
            "  readonly [key: string]: unknown;\n"
            + "\n".join(fields)
            + "\n}"
        )
    union = "\n  | ".join(message.class_name.removesuffix("Message") for message in messages)
    entries = "\n".join(
        f'  {snake_to_camel(message.class_name.removesuffix("Message"))}: "{message.message_type}",'
        for message in messages
    )
    cases = "\n".join(f'    case "{message.message_type}":' for message in messages)
    return f'''// <auto-generated />
// Generated by scripts/generate_assetlink_sdks.py; contract {digest}.

{chr(10).join(interfaces)}

export interface UnknownAssetLinkMessage {{
  readonly [key: string]: unknown;
  readonly message_type: string;
}}

export type KnownAssetLinkMessage =
  | {union};

export type AssetLinkMessage = KnownAssetLinkMessage | UnknownAssetLinkMessage;
export type AssetLinkMessageKind = KnownAssetLinkMessage["message_type"] | "unknown";

export const assetLinkMessageTypes = {{
{entries}
}} as const;

export function classifyAssetLinkMessage(messageType: string): AssetLinkMessageKind {{
  switch (messageType) {{
{cases}
      return messageType;
    default:
      return "unknown";
  }}
}}

export function parseAssetLinkMessage(json: string): AssetLinkMessage {{
  const value: unknown = JSON.parse(json);
  if (!isRecord(value) || typeof value.message_type !== "string") {{
    throw new TypeError("AssetLink message must be an object with a string message_type.");
  }}
  return value as AssetLinkMessage;
}}

export function encodeAssetLinkMessage(message: AssetLinkMessage): string {{
  return JSON.stringify(message);
}}

const maximumUint64 = BigInt("{UINT64_MAX}");
const canonicalUint64 = /^(0|[1-9][0-9]*)$/;

export function parseAssetLinkUint64(value: string): bigint {{
  if (!canonicalUint64.test(value) || value.length > 20) {{
    throw new RangeError("AssetLink uint64 must be a canonical decimal value in range.");
  }}
  const parsed = BigInt(value);
  if (parsed > maximumUint64) {{
    throw new RangeError("AssetLink uint64 must be a canonical decimal value in range.");
  }}
  return parsed;
}}

export function formatAssetLinkUint64(value: bigint): string {{
  if (value < 0n || value > maximumUint64) {{
    throw new RangeError("AssetLink uint64 is outside the unsigned 64-bit range.");
  }}
  return value.toString(10);
}}

function isRecord(value: unknown): value is Record<string, unknown> {{
  return typeof value === "object" && value !== null && !Array.isArray(value);
}}
'''


